test('Go endpoints enforce ownership before cached reads and support entry edits and deletion', async ({ signedInPage: page, account }) => {
  test.skip(process.env.MIGRATION_BACKEND !== 'go', 'Run using npm run test:e2e:go.');
  const kb = await db.knowledgeBase.create({ data: { userId: account.id, name: '权限库' } });
  const headers = { Authorization: `Bearer ${account.token}` };
  const response = await page.request.post(`/api/knowledge-bases/${kb.id}/entries`, { headers, data: { title: '测试条目', content: '测试内容🙂' } });
  expect(response.ok()).toBe(true);
  const { data: entry } = await response.json();
  expect((await page.request.get(`/api/knowledge-bases/${kb.id}/entries/${entry.id}`, { headers })).ok()).toBe(true);
  expect((await page.request.get(`/api/knowledge-bases/${kb.id}/entries/${entry.id}`)).status()).toBe(401);
  const session = (await (await page.request.post(`/api/knowledge-bases/${kb.id}/chat/sessions`, { headers })).json()).data;
  expect((await page.request.post(`/api/knowledge-bases/${kb.id}/chat/extract`, { headers, data: { sessionId: randomUUID() } })).status()).toBe(404);
  await page.goto(`/knowledge-bases/${kb.id}`);
  await page.getByRole('row').filter({ hasText: '测试条目' }).getByRole('button', { name: '编辑', exact: true }).click();
  await page.getByLabel('标题', { exact: true }).fill('已编辑条目');
  await page.getByRole('button', { name: '保存', exact: true }).click();
  await expect(page.getByRole('cell', { name: '已编辑条目', exact: true })).toBeVisible();
  expect((await page.request.delete(`/api/knowledge-bases/${kb.id}/chat/sessions/${session.id}`, { headers })).ok()).toBe(true);
  expect((await page.request.delete(`/api/knowledge-bases/${kb.id}/entries/${entry.id}`, { headers })).ok()).toBe(true);
  expect(await db.knowledgeEntry.findUnique({ where: { id: entry.id } })).toBeNull();
});
